import 'liturgical_day.dart';

/// One fixed-date celebration of the sanctoral cycle.
class SanctoralEntry {
  final int month;
  final int day;
  final String name;
  final LiturgicalRank rank;
  final LiturgicalColor color;

  /// Feasts *of the Lord* outrank Sundays of Ordinary Time and of Christmas
  /// (Table of Liturgical Days, no. 5); feasts of saints do not.
  final bool ofTheLord;

  /// Holy day of obligation in universal law (canon 1246 §1). Episcopal
  /// conferences may transfer or suppress some of these, which is why the UI
  /// presents them as the general norm.
  final bool holyDayOfObligation;

  const SanctoralEntry(
    this.month,
    this.day,
    this.name, {
    this.rank = LiturgicalRank.optionalMemorial,
    this.color = LiturgicalColor.white,
    this.ofTheLord = false,
    this.holyDayOfObligation = false,
  });
}

