import java.io.FileInputStream
import java.util.Properties

plugins {
    id("com.android.application")
    // The Flutter Gradle Plugin must be applied after the Android and Kotlin Gradle plugins.
    id("dev.flutter.flutter-gradle-plugin")
}

// Release signing. Credentials live OUTSIDE the repo, in android/key.properties
// (gitignored) or in the environment for CI — never in this file and never in
// git. Both forms carry the same four values:
//
//   android/key.properties          environment
//   ----------------------          -----------
//   storeFile=/abs/path/bt.jks      BT_STORE_FILE
//   storePassword=…                 BT_STORE_PASSWORD
//   keyAlias=bibliatraditio         BT_KEY_ALIAS
//   keyPassword=…                   BT_KEY_PASSWORD
//
// Create the keystore once and keep it backed up — Play upload keys cannot be
// regenerated by hand:
//   keytool -genkey -v -keystore ~/keys/biblia-traditio.jks -storetype JKS \
//           -keyalg RSA -keysize 2048 -validity 10000 -alias bibliatraditio
//
// With neither present the release build falls back to the debug key so
// `flutter run --release` still works locally — such a build is NOT publishable,
// and the fallback announces itself in the build log.
val keystorePropertiesFile = rootProject.file("key.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) load(FileInputStream(keystorePropertiesFile))
}

fun signingValue(propertyKey: String, envKey: String): String? =
    (keystoreProperties.getProperty(propertyKey) ?: System.getenv(envKey))?.takeIf { it.isNotBlank() }

val releaseStoreFile = signingValue("storeFile", "BT_STORE_FILE")
val releaseStorePassword = signingValue("storePassword", "BT_STORE_PASSWORD")
val releaseKeyAlias = signingValue("keyAlias", "BT_KEY_ALIAS")
val releaseKeyPassword = signingValue("keyPassword", "BT_KEY_PASSWORD")
val hasReleaseSigning = releaseStoreFile != null && releaseStorePassword != null &&
        releaseKeyAlias != null && releaseKeyPassword != null

android {
    namespace = "br.com.bibliatraditio.biblia_traditio"
    // Pinned rather than inherited so a Flutter upgrade can't move the SDK
    // levels under a release. targetSdk 36 satisfies the Play Console's
    // current requirement; minSdk 24 is what sqlite3_flutter_libs needs.
    compileSdk = 36
    ndkVersion = flutter.ndkVersion

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    defaultConfig {
        // Fixed for the life of the listing — a Play app can never change it.
        applicationId = "br.com.bibliatraditio.biblia_traditio"
        minSdk = 24
        targetSdk = 36
        // versionCode/versionName come from pubspec.yaml `version:` (x.y.z+build).
        versionCode = flutter.versionCode
        versionName = flutter.versionName
    }

    signingConfigs {
        create("release") {
            if (hasReleaseSigning) {
                storeFile = file(releaseStoreFile!!)
                storePassword = releaseStorePassword
                keyAlias = releaseKeyAlias
                keyPassword = releaseKeyPassword
            }
        }
    }

    buildTypes {
        release {
            signingConfig = if (hasReleaseSigning) {
                signingConfigs.getByName("release")
            } else {
                logger.warn(
                    "⚠ Biblia Traditio: no release signing configured " +
                        "(android/key.properties or BT_* env vars) — signing with " +
                        "the debug key. This build is NOT publishable."
                )
                signingConfigs.getByName("debug")
            }
        }
    }
}

kotlin {
    compilerOptions {
        jvmTarget = org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17
    }
}

